    private void jButtonValidarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonValidarActionPerformed
        
        boolean valid = true;
        
        String nom = jTextFieldNom.getText();
        String nif = jTextFieldNif.getText();
        String cont = new String (jPasswordFieldCont.getPassword());
        
        String missatgeError = "S`ha trobat els següents errors: \n\n";
        
        if (nom.isEmpty()) {
            
            valid = false;
            missatgeError+= "El nom no pot estar buit. \n";
        }
        
        if (!cont.equals("DAW")) {
            
            valid = false;
            missatgeError+= "Contrasenya no valida. \n";
        }
        
        if (!nif.matches("\\d{8}[A-Za-z]")) {
            
            valid = false;
            missatgeError+= "El NIF no te el format correcte. \n";
        } 
        
        if (valid) {
            
            JOptionPane.showMessageDialog(this, "Les dades han estat valides.");
        
        } else {
            
            JOptionPane.showMessageDialog(this, missatgeError, "Error de validacio.", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonValidarActionPerformed

    
    
