    private void font(){
        
        int estil = java.awt.Font.PLAIN;
        
        if (jCheckBoxNegreta.isSelected() && jCheckBoxCursiva.isSelected()){
            
            estil = java.awt.Font.ITALIC | java.awt.Font.BOLD;
        } else if (jCheckBoxNegreta.isSelected()){
            
            estil = java.awt.Font.BOLD;
            
        } else if (jCheckBoxCursiva.isSelected()){
            
            estil = java.awt.Font.ITALIC;
            
        }
        
        java.awt.Font actual = jTextAreaColores.getFont();
        jTextAreaColores.setFont(new java.awt.Font(actual.getName(), estil, actual.getSize()));
    }
